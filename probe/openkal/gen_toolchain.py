#!/usr/bin/env python3
"""Write a CMake toolchain file for <arch>-openkal from the compile command mcpp
used for a plain C++ unit of a probe project (its compile_commands.json).

usage: gen_toolchain.py <compile_commands.json> <unit-suffix> <arch> <out.cmake>
"""
import json, shlex, sys

cdb, suffix, arch, out = sys.argv[1:5]
entry = next(e for e in json.load(open(cdb)) if e["file"].endswith(suffix))
argv = entry.get("arguments") or shlex.split(entry["command"])
cxx = argv[0]
cc = cxx[:-2] if cxx.endswith("++") else cxx
bindir = cxx.rsplit("/", 1)[0]

includes, flags = [], []
skip_next = False
for i, a in enumerate(argv[1:], 1):
    if skip_next:
        skip_next = False
        continue
    if a in ("-c", "-o", "-MF"):
        skip_next = True
        continue
    if a == entry["file"] or a.endswith(suffix):
        continue
    if a.startswith("-I"):
        d = a[2:]
        # libc++'s and libc++abi's own sources are the runtime's build inputs, not a user's
        if d.endswith(("/libcxx/src", "/libcxxabi/src", "/libunwind/src", "/llvm/libc")):
            continue
        includes.append(d)
        continue
    if a.startswith(("-std=", "-O", "-g", "-fprebuilt-module-path")):
        continue
    flags.append(a)

# -Xclang pairs stay together
joined = []
it = iter(flags)
for a in it:
    joined.append(a + " " + next(it) if a == "-Xclang" else a)
flags = " ".join(joined)
inc = " ".join(f"-isystem {d}" for d in includes)

open(out, "w").write(f"""# Generated by gen_toolchain.py from mcpp's compile of a probe unit for {arch}-openkal.
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR {arch})
set(CMAKE_C_COMPILER {cc})
set(CMAKE_CXX_COMPILER {cxx})
set(CMAKE_AR {bindir}/llvm-ar)
set(CMAKE_RANLIB {bindir}/llvm-ranlib)
set(CMAKE_C_COMPILER_TARGET {arch}-unknown-none-elf)
set(CMAKE_CXX_COMPILER_TARGET {arch}-unknown-none-elf)
set(OPENKAL_FLAGS "{flags} {inc}")
set(CMAKE_C_FLAGS_INIT "${{OPENKAL_FLAGS}}")
set(CMAKE_CXX_FLAGS_INIT "${{OPENKAL_FLAGS}}")
# Nothing is linked by CMake: the image is linked and sealed by mcpp.
set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)
set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH /nonexistent)
""")
print(out)
